# OBNS: makes the in-window main menu's copy of upstream's forms (OBNS/GLFORMS.md).
#
# The forms of upstream's main menu (formMain and the dialogs it opens) are copied from the build's mirror, with
# System.Windows.Forms replaced by OBNS's controls drawn with OpenGL in the game window (OpenBve.GLForms) and each
# form renamed (formMain -> GLformMain), so they compile beside the originals. Their layout and code stay upstream's;
# the only other changes point the calls that hand a Windows Forms control to the rest of OpenBVE at OBNS's
# equivalents (below). A file is rewritten only when its text changes, so builds stay incremental.
param(
    [Parameter(Mandatory = $true)][string]$Mirror,
    [Parameter(Mandatory = $true)][string]$Output
)

$source = Join-Path $Mirror 'source\OpenBVE\UserInterface'
$forms = 'formMain', 'formAbout', 'formBugReport', 'formImage', 'formImageExport', 'formRaildriverCalibration', 'formViewLog'

New-Item -ItemType Directory -Force $Output | Out-Null
$written = @{}
foreach ($file in Get-ChildItem $source -Filter 'form*.cs') {
    $text = [System.IO.File]::ReadAllText($file.FullName)
    $text = $text -replace 'System\.Windows\.Forms', 'OpenBve.GLForms'
    $text = $text -replace 'System\.ComponentModel\.ComponentResourceManager', 'OpenBve.GLForms.ComponentResourceManager'
    foreach ($form in $forms) {
        $text = $text -replace "\b$form\b", "GL$form"
    }

    # About's Close button: upstream's ends the whole program on Mono. The Windows flow is that it closes the dialog.
    if ($file.BaseName -eq 'formAbout') {
        $text = $text -replace 'Environment\.Exit\(0\);', 'Close();'
    }

    # What the forms ask of the rest of OpenBVE through Windows Forms types (a combo box to fill, a window to own a
    # plugin's settings) goes to OBNS's equivalents (GLForms\Interop.cs).
    $text = $text -replace '\bTranslations\.ListLanguages\(', 'OpenBve.GLForms.Interop.ListLanguages('
    $text = $text -replace '\bTranslations\.SelectedLanguage\(', 'OpenBve.GLForms.Interop.SelectedLanguage('
    $text = $text -replace '\bCursors\.ListCursors\(', 'OpenBve.GLForms.Interop.ListCursors('
    $text = $text -replace '\bCursors\.SelectedCursor\(', 'OpenBve.GLForms.Interop.SelectedCursor('
    $text = $text -replace '\bInputDevicePlugin\.CallPluginConfig\(this,\s*', 'OpenBve.GLForms.Interop.CallPluginConfig('
    $text = $text -replace '([\w\.]+(?:\[[^\]]+\])?)\.Config\(this\)', 'OpenBve.GLForms.Interop.Config($1)'

    $header = "// OBNS: generated by OBNS/glforms.ps1 from upstream's UserInterface\$($file.Name) - do not edit.`r`n"
    $name = 'GL' + $file.Name
    $target = Join-Path $Output $name
    $written[$name] = $true
    $new = $header + $text
    if (-not (Test-Path $target) -or [System.IO.File]::ReadAllText($target) -ne $new) {
        [System.IO.File]::WriteAllText($target, $new, (New-Object System.Text.UTF8Encoding($true)))
    }
}

# Copies of files upstream no longer has are removed.
Get-ChildItem $Output -Filter '*.cs' | Where-Object { -not $written.ContainsKey($_.Name) } | Remove-Item
Write-Host "In-window menu: $($written.Count) form file(s) in $Output"
